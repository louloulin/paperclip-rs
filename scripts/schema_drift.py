#!/usr/bin/env python3
"""schema_drift.py — plan1 D1 的红灯：本仓迁移到的 schema 还是不是 vendored 的上游 schema？

It applies the migrations **this repo actually applies** (`migrations/**.up.sql` — the vendored
`upstream/` files and this repo's `compat/` patches, merged by file stem) to a throwaway
database, snapshots the result with the *same* extractor the other side used
(`scripts/schema_snapshot.py`), and diffs that snapshot against
`contracts/upstream-schema.json`.  Exit 0 means *every* difference is registered in
`contracts/schema-deviations.tsv`, with a reason and the issue that will close it.  Why it
exists (the D1 failure it kills), the normalisation rules and the recorded counts live in
`docs/25-W0-SCHEMA-DRIFT.md`.

Differences come in four categories — `missing` / `extra` / `differs` / `apply-exception`, see
docs/25 §4.2.  A `differs:` difference is reported per object; the columns, constraints,
indexes and triggers owned by a missing or extra *table* are folded into that table's row
instead of being listed one by one.  `apply-exception:` rows are not measured here at all: they
mirror the generated `contracts/upstream-apply-exceptions.tsv` (snapshots of this machine
cannot contain objects whose statement needs `pg_bigm` / `pg_cron`), so a skip with no
registered row fails and a registered row with no skip fails too.

Registry rows are TSV, `#` comments allowed: `对象 / 类型 / 差异摘要 / 原因 / 承接 issue`.
`对象` is an exact object key or a glob (`<table>.*` in practice) and `差异摘要` starts with one
of the four categories; `原因` and `承接 issue` are mandatory — `--emit-deviations` prints
skeleton rows with those two columns *empty*, so pasting its output back can never satisfy the
check.  A row that matches no difference is stale: a warning for most categories, a hard error
for `apply-exception:`, whose rows are generated and must stay in lockstep with the exceptions
file.  The report prints how many differences each row covers.

Usage
-----
    export MULTICA_TEST_DATABASE_URL=postgres://user:pw@127.0.0.1:5432/multica_test
    python3 scripts/schema_drift.py                        # human report, exit 0/1/2
    python3 scripts/schema_drift.py --json                 # machine report
    python3 scripts/schema_drift.py --quiet                # exit code only (CI)
    python3 scripts/schema_drift.py --emit-deviations      # skeleton registry rows

    # W0-B2 exploration: the vendored upstream files alone, without this repo's
    # `migrations/compat/` patches — shows the raw gap the patches close
    python3 scripts/schema_drift.py --apply-set upstream

Exit codes
----------
    0   every difference is registered (no output under `--quiet`)
    1   drift is not fully registered, a skip is unregistered, an `apply-exception:` row is
        stale, or a migration failed unexpectedly
    2   usage / environment / parse error (no URL, no server, malformed snapshot, registry
        or exceptions file, missing files) — the check did not run, so it is not a pass

`--apply-set local` (the default) is the CI mode: exactly the set the runtime applies — every
`*.up.sql` under `migrations/`, recursively, keyed and ordered by file stem, so the vendored
`upstream/` files and this repo's `compat/` patches form one numbering space (duplicate stems
are rejected, matching `mc_db::Migrator::load_dirs`).  `--apply-set upstream` applies the
vendored upstream files alone, with no compat patches, and is lenient about extension-gated
statements — it shows what the patches are for, so it is an aid, not a gate.

Nothing here is regenerated by CI: the snapshots are inputs and this script only reads them.
It never writes to the repo and never touches the network.
"""
