def load_snapshot(path: Path) -> dict:
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise SchemaToolError(
            f"{path} is missing — build it with scripts/build_upstream_schema.py (see "
            "docs/25-W0-SCHEMA-DRIFT.md §3).  CI only reads it; it never regenerates it."
        )
    except json.JSONDecodeError as exc:
        raise SchemaToolError(f"{path} is not valid JSON: {exc}") from None
    if doc.get("format") != SNAPSHOT_FORMAT:
        raise SchemaToolError(
            f"{path}: snapshot format {doc.get('format')!r} is not the expected {SNAPSHOT_FORMAT} — "
            "the extractor changed; rebuild the snapshot deliberately instead of diffing across it"
        )
    if not doc.get("objects"):
        raise SchemaToolError(f"{path}: the snapshot has no objects — refusing to diff against nothing")
    for obj in doc["objects"]:
        if "kind" not in obj or "key" not in obj:
            raise SchemaToolError(f"{path}: malformed object row: {obj!r}")
    return doc


def object_map(snapshot: dict) -> dict[tuple[str, str], dict]:
    """`{(kind, key): definition}` from a snapshot document."""
    return {(o["kind"], o["key"]): o.get("def", {}) for o in snapshot["objects"]}


@dataclass
class DeviationRow:
    """One registered difference: `contracts/schema-deviations.tsv`."""

    key: str
    kind: str
    summary: str
    reason: str
    issue: str
    line: int
    covered: int = 0
    example: str = ""

    @property
    def category(self) -> str:
        return self.summary.split(":", 1)[0].strip()

    def matches(self, item: "DiffItem") -> bool:
        if self.kind not in (item.kind, "*") or self.category != item.category:
            return False
        return self.key == item.key or fnmatch(item.key, self.key)


def load_deviations(path: Path, *, allow_missing: bool = False) -> list[DeviationRow]:
    try:
        raw = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        if allow_missing:
            return []
        raise SchemaToolError(
            f"{path} is missing — create it (header: see TSV_PREAMBLE in this script, rows: "
            "`python3 scripts/schema_drift.py --emit-deviations`) before gating CI on this check"
        ) from None
    rows: list[DeviationRow] = []
    for lineno, line in enumerate(raw.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        parts = [p.strip() for p in line.split("\t")]
        if len(parts) != len(DEVIATION_COLUMNS):
            raise SchemaToolError(
                f"{path}:{lineno}: expected {len(DEVIATION_COLUMNS)} tab-separated columns "
                f"({', '.join(DEVIATION_COLUMNS)}), found {len(parts)}: {line[:80]!r}"
            )
        key, kind, summary, reason, issue = parts
        if not key or not kind or not summary:
            raise SchemaToolError(f"{path}:{lineno}: 对象, 类型 and 差异摘要 must not be empty")
        category = summary.split(":", 1)[0].strip()
        if category not in CATEGORIES:
            raise SchemaToolError(
                f"{path}:{lineno}: 差异摘要 must start with one of {', '.join(CATEGORIES)}, "
                f"found {category!r}"
            )
        if not reason:
            raise SchemaToolError(
                f"{path}:{lineno}: 原因 is empty — a registered difference needs a reason a "
                "reviewer can disagree with"
            )
        if not issue:
            raise SchemaToolError(
                f"{path}:{lineno}: 承接 issue is empty — a registered difference with no owner "
                "never gets closed"
            )
        rows.append(DeviationRow(key, kind, summary, reason, issue, lineno))
    return rows


def load_apply_exceptions(path: Path) -> list[DiffItem]:
    """One `apply-exception:` item per object that a skipped statement would have created."""
    try:
        raw = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        raise SchemaToolError(
            f"{path} is missing — it is generated by scripts/build_upstream_schema.py and must be "
            "checked in next to contracts/upstream-schema.json"
        ) from None
    items: dict[tuple[str, str], DiffItem] = {}
    order: list[tuple[str, str]] = []
    for line in raw.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = [p.strip() for p in line.split("\t")]
        if len(parts) < 6:
            raise SchemaToolError(
                f"{path}: malformed row (want 6 tab-separated columns): {line[:120]!r}"
            )
        file, lineno, category, reason, objects = parts[0], parts[1], parts[2], parts[3], parts[4]
        if not objects:
            raise SchemaToolError(
                f"{path}: {file}:{lineno}: the skipped statement lists no object and no "
                "`statement:<file>:<line>` fallback — it would escape the deviation registry"
            )
        for token in objects.split(","):
            kind, _, name = token.partition(":")
            if not kind.strip() or not name.strip():
                raise SchemaToolError(f"{path}: {file}:{lineno}: cannot parse object {token!r}")
            key = (kind.strip(), name.strip())
            if key in items:
                items[key].detail.append(f"also skipped at {file}:{lineno}")
                continue
            items[key] = DiffItem(
                kind=key[0],
                key=key[1],
                category="apply-exception",
                summary=(
                    "apply-exception: upstream creates this, the snapshot built here cannot — "
                    f"{collapse_ws(reason)}"
                ),
                detail=[f"{category} at {file}:{lineno}"],
                source=f"{file}:{lineno}",
            )
            order.append(key)
    return [items[k] for k in order]


def _up_sql_files(directory: Path, *, recursive: bool) -> list[Path]:
    glob = directory.rglob if recursive else directory.glob
    files = sorted(p for p in glob("*.up.sql") if p.is_file())
    if not files:
        raise SchemaToolError(
            f"no *.up.sql migrations under {directory} — an empty apply set would make every "
            "upstream object look missing for the wrong reason"
        )
    return files


def dir_migrations(directory: Path) -> list[Path]:
    """Every `*.up.sql` directly under `directory`, sorted by name."""
    return _up_sql_files(directory, recursive=False)


def merged_migrations(directory: Path) -> list[Path]:
    """The runtime's real apply set: every `*.up.sql` under `directory`, recursively, by stem.

    Mirrors `mc_db::Migrator::load_dirs` — `upstream/001_init.up.sql` and `compat/535_x.up.sql`
    share one numbering space, ordered by that stem, and a duplicate stem is an error rather
    than a silent "last one wins".
    """
    by_stem: dict[str, list[Path]] = {}
    for path in _up_sql_files(directory, recursive=True):
        by_stem.setdefault(path.stem, []).append(path)
    clashes = {stem: [str(p) for p in ps] for stem, ps in by_stem.items() if len(ps) > 1}
    if clashes:
        raise SchemaToolError(
            f"duplicate migration version(s) under {directory} — keys must be unique: {clashes}"
        )
    return [ps[0] for _, ps in sorted(by_stem.items())]


