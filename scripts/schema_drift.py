@dataclass
class DiffItem:
    kind: str
    key: str
    category: str
    summary: str
    detail: list[str] = field(default_factory=list)
    folded: dict[str, int] = field(default_factory=dict)
    source: str = ""
    #: a `differs` row whose only difference is `attnum` — the same set of columns, laid out
    #: in another order.  It is still a difference (the snapshot records position on purpose,
    #: so a reordered table is visible), but it is not a contract difference, so the report
    #: splits it out instead of letting it drown the ones that are.
    position_only: bool = False

    @property
    def ident(self) -> tuple[str, str, str]:
        return (self.key, self.kind, self.category)

    def folded_note(self) -> str:
        if not self.folded:
            return ""
        return "  (+" + ", ".join(f"{n} {k}" for k, n in sorted(self.folded.items())) + ")"

    def detail_note(self) -> str:
        if self.position_only:
            return "column order only (attnum)"
        return self.detail[0] if self.detail else ""

    def to_json(self) -> dict:
        return {
            "object": self.key,
            "kind": self.kind,
            "category": self.category,
            "summary": self.summary,
            "detail": self.detail,
            "folded": self.folded,
            "source": self.source,
            "position_only": self.position_only,
        }


def _clip(text: str, limit: int = 160) -> str:
    text = collapse_ws(text)
    return text if len(text) <= limit else text[: limit - 3] + "..."


def _compare_defs(mine: dict, theirs: dict) -> list[str]:
    """Per-field differences between two definitions of the same object."""
    detail = []
    for key in sorted(set(mine) | set(theirs)):
        a, b = mine.get(key), theirs.get(key)
        if a == b:
            continue
        if key in ("definition", "default") and (a or b):
            detail.append(f"{key}: repo={_clip(str(a))!r} upstream={_clip(str(b))!r}")
        else:
            detail.append(f"{key}: repo={a!r} upstream={b!r}")
    return detail


def diff_snapshots(mine: dict, theirs: dict) -> list[DiffItem]:
    """Compare two `object_map()`s, folding a missing/extra table's children into its row."""
    items: list[DiffItem] = []
    by_table: dict[str, DiffItem] = {}
    folded_tables: set[str] = set()

    def add_table(key: str, category: str, summary: str) -> None:
        item = DiffItem(kind="table", key=key, category=category, summary=summary)
        items.append(item)
        by_table[key] = item
        folded_tables.add(key)

    for kind, key in sorted(k for k in theirs if k[0] == "table" and k not in mine):
        add_table(
            key,
            "missing",
            "missing: present in the upstream snapshot, not created by this repo's migrations",
        )
    for kind, key in sorted(k for k in mine if k[0] == "table" and k not in theirs):
        add_table(
            key,
            "extra",
            "extra: created by this repo's migrations, absent from the upstream snapshot",
        )

    def fold_or_emit(kind: str, key: str, category: str, summary: str) -> bool:
        """Fold a child of a missing/extra table into that table's row.  True when folded."""
        if kind not in CHILD_KINDS:
            return False
        definition = mine.get((kind, key)) or theirs.get((kind, key)) or {}
        owner = definition.get("table", "")
        if owner not in folded_tables:
            return False
        by_table[owner].folded[kind] = by_table[owner].folded.get(kind, 0) + 1
        return True

    for kind, key in sorted(set(mine) & set(theirs)):
        detail = _compare_defs(mine[(kind, key)], theirs[(kind, key)])
        position_only = bool(detail) and all(d.startswith("position:") for d in detail)
        if kind == "table":
            if detail:
                items.append(
                    DiffItem(kind, key, "differs", "differs: same object, different definition", detail)
                )
            continue
        if fold_or_emit(kind, key, "differs", ""):
            continue
        if detail:
            items.append(
                DiffItem(
                    kind,
                    key,
                    "differs",
                    "differs: same object, different definition",
                    detail,
                    position_only=position_only,
                )
            )

    for kind, key in sorted(set(mine) - set(theirs)):
        if kind == "table" or fold_or_emit(kind, key, "extra", ""):
            continue
        items.append(
            DiffItem(
                kind,
                key,
                "extra",
                "extra: created by this repo's migrations, absent from the upstream snapshot",
            )
        )

    for kind, key in sorted(set(theirs) - set(mine)):
        if kind == "table" or fold_or_emit(kind, key, "missing", ""):
            continue
        items.append(
            DiffItem(
                kind,
                key,
                "missing",
                "missing: present in the upstream snapshot, not created by this repo's migrations",
            )
        )

    return items


def check_registry(
    items: list[DiffItem], rows: list[DeviationRow]
) -> tuple[list[DiffItem], list[DeviationRow], list[DeviationRow]]:
    """`(unregistered items, stale errors, stale warnings)`."""
    unregistered: list[DiffItem] = []
    for item in items:
        hits = [r for r in rows if r.matches(item)]
        if not hits:
            unregistered.append(item)
        for r in hits:
            r.covered += 1
            if not r.example:
                r.example = item.key
    stale_errors = [r for r in rows if not r.covered and r.category == "apply-exception"]
    stale_warnings = [r for r in rows if not r.covered and r.category != "apply-exception"]
    return unregistered, stale_errors, stale_warnings


def render_deviations(items: list[DiffItem]) -> str:
    """Skeleton registry rows; `原因` and `承接 issue` are empty on purpose."""
    lines = [
        "# skeleton rows from scripts/schema_drift.py --emit-deviations",
        "# 原因 / 承接 issue are empty on purpose — fill both in before adding a row to",
        "# contracts/schema-deviations.tsv, whose loader rejects empty ones.",
        "#",
    ]
    for item in sorted(items, key=lambda i: (i.category, i.kind, i.key)):
        lines.append("\t".join([item.key, item.kind, item.category + ":", "", ""]))
    return "\n".join(lines)


