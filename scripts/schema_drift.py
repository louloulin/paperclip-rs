def _render_table(rows: list[list[str]], headers: list[str], indent: str = "  ") -> list[str]:
    """Left-align `rows` under `headers`.  Stdlib only, no wrapping."""
    if not rows:
        return [f"{indent}(none)"]
    widths = [len(h) for h in headers]
    for row in rows:
        for i, cell in enumerate(row[: len(headers)]):
            widths[i] = max(widths[i], len(cell))
    lines = [indent + "  ".join(h.ljust(widths[i]) for i, h in enumerate(headers)).rstrip()]
    for row in rows:
        cells = list(row[: len(headers)]) + [""] * (len(headers) - len(row))
        lines.append(indent + "  ".join(c.ljust(widths[i]) for i, c in enumerate(cells)).rstrip())
    return lines


def print_report(
    *,
    apply_set: str,
    files: list[Path],
    report,
    snapshot: dict,
    upstream: dict,
    items: list[DiffItem],
    deviations: list[DeviationRow],
    unregistered: list[DiffItem],
    stale_errors: list[DeviationRow],
    stale_warnings: list[DeviationRow],
    keep_db: bool,
    ok: bool,
) -> None:
    meta = upstream.get("meta", {})
    print(
        f"baseline  contracts/upstream-schema.json — upstream "
        f"{str(meta.get('upstream_commit', '?'))[:12]}, {meta.get('migrations_applied', '?')} "
        f"migrations, {len(upstream['objects'])} objects"
    )
    print(
        f"apply set {apply_set} — {len(files)} file(s), {report.statements} statements, "
        f"{len(report.applied)} applied, {len(report.skipped)} skipped"
    )
    print(
        f"scratch   {snapshot['meta']['database']}{'' if keep_db else ' (dropped)'} on "
        f"PostgreSQL {snapshot['meta']['server_version']} — {len(snapshot['objects'])} objects"
    )
    print()

    if items:
        rows = []
        for item in sorted(items, key=lambda i: (i.category, i.kind, i.key)):
            detail = item.folded_note().strip() or item.detail_note()
            rows.append([item.category, item.kind, item.key, detail])
        print(f"differences ({len(items)}):")
        for line in _render_table(rows, ["category", "kind", "object", "detail"]):
            print(line)
    else:
        print("differences: none — the two schemas are identical")

    by_category: dict[str, int] = {}
    for item in items:
        by_category[item.category] = by_category.get(item.category, 0) + 1
    if by_category:
        print()
        print("by category: " + ", ".join(f"{k}={v}" for k, v in sorted(by_category.items())))
        order_only = sum(1 for i in items if i.position_only)
        if order_only:
            print(
                f"            ({order_only} of the differs rows are column order only — same columns, "
                "different attnum; kept because a reordered table is a difference, not a contract change)"
            )
        folded: dict[str, int] = {}
        for item in items:
            for kind, count in item.folded.items():
                folded[kind] = folded.get(kind, 0) + count
        if folded:
            print(
                "            ("
                + ", ".join(f"{v} {k}" for k, v in sorted(folded.items()))
                + " folded into the missing/extra table rows)"
            )

    if report.unexpected:
        print()
        print(f"unexpected migration failures ({len(report.unexpected)}):")
        for s in report.unexpected:
            print(f"  {s.file}:{s.line} {collapse_ws(s.reason)}")
    if report.notices:
        print()
        print(f"guard notices ({len(report.notices)}) — upstream swallowed these at runtime:")
        for name, notice in report.notices:
            print(f"  {name}: {collapse_ws(notice)}")

    print()
    print(
        f"registry  {len(deviations)} row(s): {sum(1 for r in deviations if r.covered)} matched, "
        f"{len(stale_warnings)} stale (warning), {len(stale_errors)} stale (error)"
    )
    for row in stale_errors:
        print(f"  ERROR stale apply-exception row at line {row.line}: {row.key} ({row.kind})")
    for row in stale_warnings[:10]:
        print(f"  warn  stale row at line {row.line}: {row.key} ({row.kind}, {row.category})")

    if unregistered:
        print()
        print(f"unregistered differences ({len(unregistered)}) — run this to get skeleton rows:")
        print("  python3 scripts/schema_drift.py --emit-deviations")
        for line in _render_table(
            [[i.category, i.kind, i.key] for i in sorted(unregistered, key=lambda i: (i.kind, i.key))],
            ["category", "kind", "object"],
        ):
            print(line)

    print()
    print("OK — every difference is registered" if ok else "FAIL — drift is not fully registered")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument(
        "--db-url",
        default=os.environ.get("MULTICA_TEST_DATABASE_URL", ""),
        help="postgres:// URL of an existing database on the target server; the scratch database "
        "is created next to it (env: MULTICA_TEST_DATABASE_URL).  The password reaches the psql "
        "child through PGPASSWORD, never through its argv, so it cannot show up in `ps`.",
    )
    ap.add_argument("--db-name", default=DEFAULT_DB_NAME, help="name of the scratch database")
    ap.add_argument("--migrations", default=str(ROOT / DEFAULT_MIGRATIONS))
    ap.add_argument("--upstream-migrations", default=str(ROOT / DEFAULT_UPSTREAM_MIGRATIONS))
    ap.add_argument("--upstream-schema", default=str(ROOT / DEFAULT_UPSTREAM_SCHEMA))
    ap.add_argument("--deviations", default=str(ROOT / DEFAULT_DEVIATIONS))
    ap.add_argument("--exceptions", default=str(ROOT / DEFAULT_EXCEPTIONS))
    ap.add_argument(
        "--apply-set",
        choices=("local", "upstream"),
        default="local",
        help="local (default, the CI mode): the runtime's real apply set — every *.up.sql under "
        "migrations/, recursively, merged and ordered by file stem (upstream/ + compat/).  "
        "upstream: the vendored migrations/upstream/*.up.sql alone, no compat patches (W0-B2 "
        "exploration; extension-gated statements are tolerated).",
    )
    ap.add_argument(
        "--lenient",
        action="store_true",
        help="record unexpected migration failures and carry on instead of failing the run",
    )
    ap.add_argument("--keep-db", action="store_true", help="leave the scratch database behind")
    ap.add_argument(
        "--emit-deviations",
        action="store_true",
        help="print skeleton registry rows for the unregistered differences",
    )
    ap.add_argument("--json", action="store_true", help="machine-readable report on stdout")
    ap.add_argument("--quiet", action="store_true", help="print nothing; the exit code is the answer")
    args = ap.parse_args(argv)

    if not args.db_url:
        sys.stderr.write("error: no database URL: pass --db-url or set MULTICA_TEST_DATABASE_URL\n")
        return 2

    try:
        parse_db_url(args.db_url)
        upstream = load_snapshot(Path(args.upstream_schema))
        deviations = load_deviations(Path(args.deviations), allow_missing=args.emit_deviations)
        exceptions = load_apply_exceptions(Path(args.exceptions))
        if args.apply_set == "upstream":
            files = dir_migrations(Path(args.upstream_migrations))
        else:
            files = merged_migrations(Path(args.migrations))
    except SchemaToolError as exc:
        sys.stderr.write(f"error: {exc}\n")
        return 2

    # `local` is strict: the runtime's own set must apply cleanly.  `upstream` is the
    # exploration mode and tolerates extension-gated statements, as does `--lenient`.
    strict = not (args.lenient or args.apply_set == "upstream")

    try:
        with ScratchDatabase(args.db_url, args.db_name, keep=args.keep_db) as db:
            available = db.available_extensions()
            report = apply_migrations(db, files, available=available, strict=False)
            snapshot = build_snapshot(
                db,
                label=f"repo-{args.apply_set}",
                source="the migrations/*.up.sql files this repo applies",
            )
    except SchemaToolError as exc:
        sys.stderr.write(f"error: {exc}\n")
        return 2

    items = diff_snapshots(object_map(snapshot), object_map(upstream)) + exceptions
    unregistered, stale_errors, stale_warnings = check_registry(items, deviations)
    unexpected_failure = bool(report.unexpected) and strict
    ok = not unregistered and not stale_errors and not unexpected_failure

    if args.emit_deviations and not args.quiet and not args.json:
        print(render_deviations(unregistered))

    if args.json:
        counts: dict[str, int] = {}
        for item in items:
            counts[item.category] = counts.get(item.category, 0) + 1
        payload = {
            "ok": ok,
            "apply_set": args.apply_set,
            "database": snapshot["meta"]["database"],
            "server_version": snapshot["meta"]["server_version"],
            "upstream": {
                "snapshot": args.upstream_schema,
                "commit": upstream["meta"].get("upstream_commit", ""),
                "repo": upstream["meta"].get("upstream_repo", ""),
                "migrations": upstream["meta"].get("migrations_applied"),
                "objects": len(upstream["objects"]),
                "sha256": sha256_of(Path(args.upstream_schema)),
            },
            "repo": {
                "objects": len(snapshot["objects"]),
                "migrations": [{"file": p.name, "sha256": sha256_of(p)} for p in files],
                "statements": report.statements,
                "applied": len(report.applied),
                "extensions": snapshot["meta"]["extensions"],
            },
            "skipped": [
                {
                    "file": s.file,
                    "line": s.line,
                    "category": s.category,
                    "reason": collapse_ws(s.reason),
                    "objects": [f"{k}:{v}" for k, v in skip_object_keys(s)],
                }
                for s in report.skipped
            ],
            "unexpected_skips": [
                f"{s.file}:{s.line} {s.category} {collapse_ws(s.reason)}" for s in report.unexpected
            ],
            "guard_notices": [f"{name}: {collapse_ws(n)}" for name, n in report.notices],
            "counts": counts,
            "position_only": sum(1 for i in items if i.position_only),
            "folded": {
                k: sum(i.folded.get(k, 0) for i in items)
                for k in sorted({k for i in items for k in i.folded})
            },
            "differences": [i.to_json() for i in items],
            "unregistered": [i.to_json() for i in unregistered],
            "registry": {
                "file": args.deviations,
                "rows": len(deviations),
                "matched": sum(1 for r in deviations if r.covered),
                "stale_errors": [
                    {"line": r.line, "object": r.key, "kind": r.kind, "category": r.category}
                    for r in stale_errors
                ],
                "stale_warnings": [
                    {"line": r.line, "object": r.key, "kind": r.kind, "category": r.category}
                    for r in stale_warnings
                ],
                "coverage": [
                    {
                        "line": r.line,
                        "object": r.key,
                        "kind": r.kind,
                        "category": r.category,
                        "covers": r.covered,
                        "example": r.example,
                    }
                    for r in deviations
                ],
            },
            "extensions_available": sorted(available),
        }
        json.dump(payload, sys.stdout, indent=2, ensure_ascii=False)
        sys.stdout.write("\n")
    elif not args.quiet and not args.emit_deviations:
        print_report(
            apply_set=args.apply_set,
            files=files,
            report=report,
            snapshot=snapshot,
            upstream=upstream,
            items=items,
            deviations=deviations,
            unregistered=unregistered,
            stale_errors=stale_errors,
            stale_warnings=stale_warnings,
            keep_db=args.keep_db,
            ok=ok,
        )

    return 0 if ok else 1


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except BrokenPipeError:  # `| head` — close stdout without a traceback
        try:
            sys.stdout.close()
        finally:
            os._exit(0)
    except KeyboardInterrupt:
        raise SystemExit(130)
