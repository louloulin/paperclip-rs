//! Integration tests that wire `pc-typescript-gen` to the real `pc-openapi`
//! DTO registry (35 schemas registered by `register_core_dtos`).

use pc_openapi::{register_core_dtos, OpenApiRegistry, CORE_DTO_NAMES};
use pc_typescript_gen::{generate_typescript_types, schema_to_typescript, schema_to_type_expr};
use serde_json::json;

fn build_real_spec() -> pc_openapi::OpenApiSpec {
    let mut reg = OpenApiRegistry::builder();
    register_core_dtos(&mut reg);
    reg.build()
}

#[test]
fn real_spec_generates_for_all_35_dtos() {
    let spec = build_real_spec();
    let ts = generate_typescript_types(&spec);
    for name in CORE_DTO_NAMES {
        let pascal = to_pascal(name);
        assert!(
            ts.contains(&format!("export interface {pascal}"))
                || ts.contains(&format!("export type {pascal}")),
            "missing DTO {name} (PascalCase {pascal}) in generated output"
        );
    }
}

#[test]
fn real_spec_output_is_byte_stable() {
    let spec = build_real_spec();
    let ts1 = generate_typescript_types(&spec);
    let ts2 = generate_typescript_types(&spec);
    assert_eq!(ts1, ts2, "generator output is not deterministic");
}

#[test]
fn real_spec_header_present() {
    let spec = build_real_spec();
    let ts = generate_typescript_types(&spec);
    assert!(ts.starts_with("// Generated by pc-typescript-gen (R518)"));
}

#[test]
fn real_spec_no_empty_interface_bodies() {
    // Schemas without named properties should fall back to `type X = ...`,
    // never `interface X { }`. We assert that any `interface X {` line is
    // followed by an indented property (not immediately by `}`).
    let spec = build_real_spec();
    let ts = generate_typescript_types(&spec);
    let mut in_interface = false;
    let mut saw_property = false;
    for line in ts.lines() {
        if line.starts_with("export interface ") {
            in_interface = true;
            saw_property = false;
            continue;
        }
        if in_interface {
            if line.starts_with("  ") && line.ends_with(";") {
                saw_property = true;
            } else if line == "}" {
                assert!(
                    saw_property,
                    "interface with empty body found:\n{ts}"
                );
                in_interface = false;
            }
        }
    }
    // Verify we also emitted type aliases for non-object DTOs.
    assert!(ts.contains("export type "), "no type aliases emitted");
}

#[test]
fn real_spec_contains_at_least_33_exports() {
    let spec = build_real_spec();
    let ts = generate_typescript_types(&spec);
    let export_count = ts.matches("export ").count();
    assert!(
        export_count >= CORE_DTO_NAMES.len(),
        "expected at least {} exports, got {}",
        CORE_DTO_NAMES.len(),
        export_count
    );
}

