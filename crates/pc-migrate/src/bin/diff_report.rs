#![forbid(unsafe_code)]

//! Migration diff-report — emit a markdown report comparing Rust migrations
//! to the Node paperclip DB baseline (109 tables → 172 tables).
//!
//! Output: `MIGRATION_DIFF.md` listing every migration with its table count
//! delta and rationale category.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum MigrationCategory {
    /// Initial schema (Node 109 tables).
    Initial,
    /// Adds a new table.
    NewTable,
    /// Adds a column to existing table.
    NewColumn,
    /// Creates an index.
    NewIndex,
    /// Migration of existing data (UPDATE statements).
    DataMigration,
    /// Drops / deprecates something.
    Deprecation,
    /// Other / unknown.
    Other,
}

impl MigrationCategory {
    fn from_filename(name: &str) -> Self {
        // Initial schema: filename starting with "0000" or "0001_"
        if name.starts_with("0000_") {
            return Self::Initial;
        }
        // Drop checks first (more specific than generic keyword match)
        if name.contains("drop") {
            return Self::Deprecation;
        }
        if name.contains("index") || name.contains("idx_") {
            return Self::NewIndex;
        }
        if name.contains("create_table") || name.contains("create_") {
            return Self::NewTable;
        }
        if name.contains("add_") || name.contains("alter_") {
            return Self::NewColumn;
        }
        Self::Other
    }

    fn as_str(self) -> &'static str {
        match self {
            Self::Initial => "initial",
            Self::NewTable => "new-table",
            Self::NewColumn => "new-column",
            Self::NewIndex => "new-index",
            Self::DataMigration => "data-migration",
            Self::Deprecation => "deprecation",
            Self::Other => "other",
        }
    }
}

#[derive(Debug)]
struct MigrationEntry {
    filename: String,
    category: MigrationCategory,
    table_count: usize,
}

fn analyze_one(path: &Path) -> MigrationEntry {
    let content = std::fs::read_to_string(path).unwrap_or_default();
    let table_count = content.matches("CREATE TABLE").count()
        + content.matches("CREATE TABLE IF NOT EXISTS").count();
    let filename = path
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("")
        .to_owned();
    let category = MigrationCategory::from_filename(&filename);
    MigrationEntry {
        filename,
        category,
        table_count,
    }
}

pub fn analyze(migrations_dir: &Path) -> Vec<MigrationEntry> {
    let mut entries = Vec::new();
    let Ok(read_dir) = std::fs::read_dir(migrations_dir) else {
        return entries;
    };
    for entry in read_dir.flatten() {
        let path = entry.path();
        if path.extension().and_then(|s| s.to_str()) == Some("sql") {
            entries.push(analyze_one(&path));
        }
    }
    entries.sort_by(|a, b| a.filename.cmp(&b.filename));
    entries
}

fn render_markdown(
    entries: &[MigrationEntry],
    upstream_baseline: usize,
) -> String {
    let mut out = String::new();
    out.push_str("# paperclip-rs Migration Diff Report\n\n");
    out.push_str(&format!(
        "Generated: {}\n\n",
        chrono::Utc::now().to_rfc3339()
    ));

    let total_tables: usize = entries.iter().map(|e| e.table_count).sum();
    let mut by_category: BTreeMap<&str, usize> = BTreeMap::new();
    for e in entries {
        *by_category.entry(e.category.as_str()).or_insert(0) += 1;
    }

    out.push_str("## Summary\n\n");
    out.push_str(&format!("- Total migrations: {}\n", entries.len()));
    out.push_str(&format!(
        "- Upstream Node baseline tables: {}\n",
        upstream_baseline
    ));
    out.push_str(&format!(
        "- Rust migrations CREATE TABLE count: {}\n",
        total_tables
    ));
    out.push_str("- Distribution by category:\n");
    for (cat, count) in &by_category {
        out.push_str(&format!("  - `{cat}`: {count}\n"));
    }
    out.push_str("\n## Per-Migration\n\n");
    out.push_str("| # | File | Category | CREATE TABLE |\n");
    out.push_str("|---|------|----------|-------------:|\n");
    for (i, e) in entries.iter().enumerate() {
        out.push_str(&format!(
            "| {} | `{}` | {} | {} |\n",
            i + 1,
            e.filename,
            e.category.as_str(),
            e.table_count
        ));
    }
    out.push_str("\n## Notes\n\n");
    out.push_str("- Initial migration is generated by drizzle from current schema\n");
    out.push_str("- Subsequent migrations are additive (new tables / columns / indexes)\n");
    out.push_str("- Deprecations are scheduled separately (no production drops yet)\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn categorize_initial() {
        assert_eq!(MigrationCategory::from_filename("0000_init.sql"), MigrationCategory::Initial);
    }

    #[test]
    fn categorize_create() {
        assert_eq!(
            MigrationCategory::from_filename("0005_create_users.sql"),
            MigrationCategory::NewTable
        );
    }

    #[test]
    fn categorize_index() {
        assert_eq!(
            MigrationCategory::from_filename("0010_idx_users_email.sql"),
            MigrationCategory::NewIndex
        );
    }

    #[test]
    fn categorize_drop() {
        assert_eq!(
            MigrationCategory::from_filename("0050_drop_legacy.sql"),
            MigrationCategory::Deprecation
        );
    }

    #[test]
    fn categorize_other() {
        assert_eq!(
            MigrationCategory::from_filename("0099_seeds.sql"),
            MigrationCategory::Other
        );
    }

    #[test]
    fn render_includes_summary_and_table() {
        let entries = vec![
            MigrationEntry {
                filename: "0000_init.sql".to_string(),
                category: MigrationCategory::Initial,
                table_count: 50,
            },
            MigrationEntry {
                filename: "0050_idx_users.sql".to_string(),
                category: MigrationCategory::NewIndex,
                table_count: 0,
            },
        ];
        let md = render_markdown(&entries, 109);
        assert!(md.contains("# paperclip-rs Migration Diff Report"));
        assert!(md.contains("Total migrations: 2"));
        assert!(md.contains("Upstream Node baseline tables: 109"));
        assert!(md.contains("`0000_init.sql`"));
        assert!(md.contains("`0050_idx_users.sql`"));
    }
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let dir = args
        .get(1)
        .cloned()
        .unwrap_or_else(|| "../pc-db/migrations/drizzle".into());
    let output = args
        .get(2)
        .cloned()
        .unwrap_or_else(|| "MIGRATION_DIFF.md".into());
    let upstream_baseline: usize = args
        .get(3)
        .and_then(|s| s.parse().ok())
        .unwrap_or(109);

    let dir = PathBuf::from(dir);
    let output = PathBuf::from(output);
    let entries = analyze(&dir);
    let md = render_markdown(&entries, upstream_baseline);
    if let Err(e) = std::fs::write(&output, md.as_bytes()) {
        eprintln!("write {} failed: {e}", output.display());
        std::process::exit(1);
    }
    println!("Wrote migration diff report to {}", output.display());
    println!("  Total: {}", entries.len());
    println!("  Tables: {}", entries.iter().map(|e| e.table_count).sum::<usize>());
}